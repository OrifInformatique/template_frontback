package ch.sectioninformatique.template.auth;

import java.net.URI;
import java.time.Duration;
import java.util.List;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.http.HttpHeaders;
import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseCookie;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RequestParam;
import org.springframework.web.bind.annotation.RestController;

import ch.sectioninformatique.template.auth.AuthExceptions.OAuth2LoginResultNotFoundException;
import ch.sectioninformatique.template.user.UserDto;
import ch.sectioninformatique.template.user.UserService;
import jakarta.servlet.http.HttpServletRequest;
import jakarta.servlet.http.HttpSession;
import lombok.RequiredArgsConstructor;

/**
 * Azure OAuth2 login, delegated to spring-auth (same paths as spring-auth's
 * OAuth2 endpoints).
 *
 * The flow is a redirect dance between the frontend, this backend, spring-auth
 * and Azure:
 * 1. GET /oauth2/login/azure redirects the browser to spring-auth's Azure login,
 *    with /oauth2/callback as the URL to come back to (AFTER_OAUTH2_LOGIN_URL)
 * 2. After the Azure login, spring-auth redirects the browser to
 *    GET /oauth2/callback with a temporary auth code; the backend exchanges it
 *    for the user and its tokens, keeps them in the HTTP session and redirects
 *    the browser to the frontend (AFTER_OAUTH2_LOGIN_FRONTEND_CALLBACK)
 * 3. The frontend calls POST /oauth2/token (with the session cookie) to get the
 *    user and its tokens, once: the session data is then removed
 */
@RequestMapping("/oauth2")
@RequiredArgsConstructor
@RestController
public class OAuth2Controller {

    private static final Logger log = LoggerFactory.getLogger(OAuth2Controller.class);

    /** Session attributes holding the result of the Azure login until the frontend takes it */
    private static final String LOGGED_USER_SESSION_KEY = "loggedUser";
    private static final String REFRESH_TOKEN_SESSION_KEY = "refresh_token";

    private final AuthClient authClient;

    private final UserService userService;

    @Value("${SECURITY_JWT_TOKEN_REFRESH_TOKEN_LIFETIME}")
    private Duration refreshTokenLifeTime;

    @Value("${AFTER_OAUTH2_LOGIN_FRONTEND_CALLBACK}")
    private String afterOauth2LoginFrontendCallback;

    /**
     * Starts an Azure login: redirects the browser to spring-auth's Azure login,
     * which will come back to {@code /oauth2/callback}.
     *
     * @return 302 Found to spring-auth
     */
    @GetMapping("/login/azure")
    public ResponseEntity<Void> loginWithAzure() {
        URI loginUri = authClient.buildAzureLoginUri();
        log.debug("Redirecting to spring-auth Azure login endpoint: {}", loginUri);
        return ResponseEntity.status(HttpStatus.FOUND).location(loginUri).build();
    }

    /**
     * Callback of spring-auth after a successful Azure login (a browser
     * redirect, hence GET): exchanges the temporary auth code for the user and
     * its tokens, keeps them in the session, and redirects to the frontend.
     *
     * @param authCode temporary auth code generated by spring-auth
     * @param userId   spring-auth id of the logged user
     * @param request  current request, for the session
     * @return 302 Found to the frontend callback URL
     */
    @GetMapping("/callback")
    public ResponseEntity<Void> callback(@RequestParam String authCode, @RequestParam Long userId,
            HttpServletRequest request) {
        log.debug("OAuth2 login successful, using authcode to get tokens");
        AuthCodeDto authCodeDto = AuthCodeDto.builder()
                .code(authCode)
                .userId(userId)
                .build();

        // Exchange the auth code with spring-auth: user with its access token,
        // refresh token in a Set-Cookie header
        ResponseEntity<UserDto> response = authClient.getTokenWithAuthCode(authCodeDto).block();
        UserDto user = response.getBody();

        HttpSession session = request.getSession();
        List<String> cookies = response.getHeaders().get(HttpHeaders.SET_COOKIE);
        if (cookies != null) {
            cookies.stream()
                    .filter(cookie -> cookie.startsWith("refresh_token="))
                    .findFirst()
                    .ifPresent(cookie -> session.setAttribute(REFRESH_TOKEN_SESSION_KEY, cookie));
        }

        // Same response as a standard login: the spring-auth user (with its token),
        // completed with its local roles and permissions. The local user is found
        // by its spring-auth id, or created.
        UserDto loggedUser = userService.addLocalRolesAndPermissions(user, user.getId());
        session.setAttribute(LOGGED_USER_SESSION_KEY, loggedUser);

        log.debug("Redirecting to: {}", afterOauth2LoginFrontendCallback);
        return ResponseEntity.status(HttpStatus.FOUND)
                .location(URI.create(afterOauth2LoginFrontendCallback))
                .build();
    }

    /**
     * Returns the result of the Azure login kept in the session: the user with
     * its access token, and the refresh token in a cookie. Single use: the
     * session data is removed.
     *
     * @param request current request, for the session
     * @return 200 with the logged user, 401 if no Azure login is waiting
     */
    @PostMapping("/token")
    public ResponseEntity<UserDto> token(HttpServletRequest request) {
        HttpSession session = request.getSession(false);
        UserDto loggedUser = session != null ? (UserDto) session.getAttribute(LOGGED_USER_SESSION_KEY) : null;
        String refreshTokenCookie = session != null ? (String) session.getAttribute(REFRESH_TOKEN_SESSION_KEY) : null;
        if (loggedUser == null || refreshTokenCookie == null) {
            throw new OAuth2LoginResultNotFoundException();
        }
        // Single use: the tokens must not stay in the session
        session.removeAttribute(LOGGED_USER_SESSION_KEY);
        session.removeAttribute(REFRESH_TOKEN_SESSION_KEY);

        String refreshToken = refreshTokenCookie
                .substring("refresh_token=".length())
                .split(";")[0];
        ResponseCookie cookie = ResponseCookie.from("refresh_token", refreshToken)
                .httpOnly(true)
                .secure(true)
                .path("/auth/refresh")
                .maxAge(refreshTokenLifeTime)
                .sameSite("None")
                .build();

        return ResponseEntity.ok()
                .header(HttpHeaders.SET_COOKIE, cookie.toString())
                .body(loggedUser);
    }
}
